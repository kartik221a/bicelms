#!/usr/bin/env python3
"""Build contact sheet images from Stitch screenshots + extract design system md."""
import json
import pathlib
from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path("/home/z/my-project")
SHOTS = ROOT / "download/stitch-designs/screenshots"
OUT = ROOT / "download/stitch-designs"
REG = json.loads((OUT / "registry.json").read_text())

try:
    FONT = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 22)
    FONT_S = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 15)
except Exception:
    FONT = FONT_S = ImageFont.load_default()

LABEL_H = 34


def make_sheet(items, cols, cell_w, crop_top_px, out_path, quality=72):
    cells = []
    for r in items:
        p = SHOTS / f"{r['slug']}.png"
        if not p.exists():
            continue
        im = Image.open(p).convert("RGB")
        w, h = im.size
        crop_h = min(crop_top_px, h)
        im = im.crop((0, 0, w, crop_h))
        ratio = cell_w / w
        im = im.resize((cell_w, max(1, int(crop_h * ratio))), Image.LANCZOS)
        cells.append((r, im))
    if not cells:
        return
    rows = (len(cells) + cols - 1) // cols
    cell_h = max(im.size[1] for _, im in cells)
    pad = 18
    sheet_w = cols * cell_w + (cols + 1) * pad
    sheet_h = rows * (cell_h + LABEL_H) + (rows + 1) * pad + 60
    sheet = Image.new("RGB", (sheet_w, sheet_h), (15, 23, 42))
    d = ImageDraw.Draw(sheet)
    d.text((pad, 16), "BICE LMS - Stitch Design System (Google Stitch, project 9891734431591622481)", font=FONT, fill=(255, 255, 255))
    y0 = 60
    for i, (r, im) in enumerate(cells):
        c, rr = i % cols, i // cols
        x = pad + c * (cell_w + pad)
        y = y0 + rr * (cell_h + LABEL_H + pad)
        sheet.paste(im, (x, y))
        label = f"{r['device'][:2]}  {r['slug']}"
        d.text((x + 2, y + cell_h + 6), label, font=FONT_S, fill=(148, 163, 184))
    sheet.save(out_path, "JPEG", quality=quality)
    print(out_path, sheet.size)


desktop = [r for r in REG if r["device"] == "DESKTOP"]
mobile = [r for r in REG if r["device"] in ("MOBILE",) or r["slug"].endswith("mobile")]
tablet = [r for r in REG if r["device"] == "TABLET" and r not in mobile]

make_sheet(desktop, cols=3, cell_w=430, crop_top_px=1550, out_path=OUT / "contact-sheet-desktop.jpg")
make_sheet(mobile + tablet, cols=4, cell_w=250, crop_top_px=2400, out_path=OUT / "contact-sheet-mobile-tablet.jpg")

# extract design system markdown from first generation response
raw = json.loads((ROOT / "stitch-responses/generate_screen_from_text__1001.json").read_text())
txt = raw.get("result", {}).get("content", [{}])[0].get("text", "")
try:
    inner = json.loads(txt)
    ds = None
    for oc in inner.get("outputComponents", []):
        if "designSystem" in oc:
            ds = oc["designSystem"]
            break
    if ds:
        md = [
            "# BICE LMS - Stitch Design System",
            "",
            f"**Design system id (Stitch):** `{ds.get('name')}`",
            f"**Display name:** {ds.get('designSystem', {}).get('displayName', '')}",
            "",
            "This design system was auto-generated by Google Stitch for project "
            "`BICE LMS Platform` (9891734431591622481) and is applied to ALL 24 screens.",
            "",
            ds.get("designSystem", {}).get("styleGuidelines", ""),
        ]
        (OUT / "DESIGN.md").write_text("\n".join(md), encoding="utf-8")
        print("DESIGN.md written:", len("\n".join(md)), "chars")
except Exception as e:
    print("DS extraction failed:", e)
